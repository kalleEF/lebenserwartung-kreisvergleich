  const dicts = { de, en };
  let lang = "de";

  function t(key, vars) {
    const d = dicts[lang] || de;
    let s = d[key];
    if (s === undefined) s = de[key];
    if (s === undefined) return key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : m));
    return s;
  }

  const fmtCache = {};
  function nf(digits) {
    const k = lang + digits;
    if (!fmtCache[k]) {
      fmtCache[k] = new Intl.NumberFormat(lang === "de" ? "de-DE" : "en-GB", {
        minimumFractionDigits: digits, maximumFractionDigits: digits
      });
    }
    return fmtCache[k];
  }
  function num(v, digits = 1) {
    if (v === null || v === undefined || Number.isNaN(v)) return "–";
    return nf(digits).format(v).replace(/^-/, "−");
  }
  function signed(v, digits = 1) {
    if (v === null || v === undefined || Number.isNaN(v)) return "–";
    const s = nf(digits).format(Math.abs(v));
    if (Math.abs(v) < Math.pow(10, -digits) / 2) return nf(digits).format(0);
    return (v > 0 ? "+" : "−") + s;
  }
  function int(v) {
    if (v === null || v === undefined || Number.isNaN(v)) return "–";
    return nf(0).format(Math.round(v));
  }

  function setLang(l) { lang = dicts[l] ? l : "de"; }
  function getLang() { return lang; }

  window.LE = window.LE || {};
  window.LE.i18n = { t, num, signed, int, setLang, getLang };
